// Renders public/logo.svg into the PNG icons used by iOS (apple-touch-icon), the web manifest and favicons.
// Run: node scripts/make-icons.mjs
import sharp from "sharp";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const svg = readFileSync("public/logo.svg");
mkdirSync("public/icons", { recursive: true });

const render = (size, file) => sharp(svg, { density: 384 }).resize(size, size).png().toFile(`public/icons/${file}`);

// Maskable icon: shrink art into the central 80% "safe zone" over the same background colour.
const maskable = async (size, file) => {
  const inner = Math.round(size * 0.8);
  const art = await sharp(svg, { density: 384 }).resize(inner, inner).png().toBuffer();
  await sharp({ create: { width: size, height: size, channels: 4, background: "#0a0d08" } })
    .composite([{ input: art, gravity: "center" }]).png().toFile(`public/icons/${file}`);
};

await Promise.all([
  render(180, "apple-touch-icon.png"), // iOS home screen (iOS rounds the corners itself)
  render(192, "icon-192.png"),
  render(512, "icon-512.png"),
  render(1024, "icon-1024.png"),
  render(32, "favicon-32.png"),
  maskable(512, "icon-maskable-512.png"),
]);
writeFileSync("public/icons/.generated", "Generated by scripts/make-icons.mjs from public/logo.svg\n");
console.log("icons written to public/icons");
